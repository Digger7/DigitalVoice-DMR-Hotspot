// QR1676Encode encodes the 7-bit value (b>>1) into a 2-byte EMB block.
func QR1676Encode(b byte) [2]byte {
	value := (b >> 1) & 0x7F
	cksum := encodingTable1676[value]
	return [2]byte{byte(cksum >> 8), byte(cksum & 0xFF)}
}

// QR1676Decode decodes a 2-byte EMB block back to the full EMB byte.
func QR1676Decode(data []byte) byte {
	code := uint32(data[0])<<7 | uint32(data[1])>>1
	best := 0
	bestDist := 99
	for m, cksum := range encodingTable1676 {
		cw := (uint32(cksum>>8) << 7) | (uint32(cksum&0xFF) >> 1)
		d := Popcount(code ^ cw)
		if d < bestDist {
			bestDist = d
			best = m
		}
	}
	cksum := encodingTable1676[best]
	return byte(cksum >> 8)
}

// Golay2087Encode turns the 8-bit slot type (CC<<4|DT) into 3 bytes.
func Golay2087Encode(slotType byte) [3]byte {
	cksum := encodingTable2087[slotType]
	return [3]byte{slotType, byte(cksum & 0xFF), byte(cksum >> 8)}
}

// Golay2087Decode decodes a 3-byte slot type block back to CC<<4|DT.
func Golay2087Decode(data []byte) byte {
	code := uint32(data[0])<<11 | uint32(data[1])<<3 | (uint32(data[2])>>5)&0x07
	best := 0
	bestDist := 99
	for m, cksum := range encodingTable2087 {
		cw := (uint32(m) << 11) | (uint32(cksum&0xFF) << 3) | ((uint32(cksum>>8) >> 5) & 0x07)
		d := Popcount(code ^ cw)
		if d < bestDist {
			bestDist = d
			best = m
		}
	}
	return byte(best)
}
